using ApexPost.Domain.Entities;
using ApexPost.Domain.ValueObjects;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace ApexPost.Infrastructure.Persistence.Sql.Configurations;

public sealed class CounterTransactionConfiguration
	: IEntityTypeConfiguration<TransactionBasket>
{
	private const string ReversalReasonField = "_reversalReason";
	private const string TaxRatesField = "_taxRates";

	public void Configure(EntityTypeBuilder<TransactionBasket> builder)
	{
		builder.ToTable("CounterTransactions", table =>
		{
			table.HasCheckConstraint(
				"CK_CounterTransactions_Status",
				"[Status] IN ('Open', 'Paid', 'Voided', 'Refunded')");
			table.HasCheckConstraint(
				"CK_CounterTransactions_ReversalReason",
				"([Status] IN ('Voided', 'Refunded') AND [ReversalReason] IS NOT NULL) " +
				"OR ([Status] IN ('Open', 'Paid') AND [ReversalReason] IS NULL)");
			table.HasCheckConstraint(
				"CK_CounterTransactions_SaleDetails",
				"([CounterId] IS NULL AND [ClerkStaffId] IS NULL AND [PaymentMethod] IS NULL) " +
				"OR ([CounterId] IS NOT NULL AND [ClerkStaffId] IS NOT NULL AND [PaymentMethod] IS NOT NULL)");
		});

		// The ID is generated by the client, which makes a repeated submission
		// a primary-key conflict rather than a second sale.
		builder.HasKey(transaction => transaction.Id);
		builder.Property(transaction => transaction.Id)
			.HasColumnName("TransactionId")
			.ValueGeneratedNever();

		builder.Property(transaction => transaction.Currency)
			.HasColumnType("char(3)")
			.IsUnicode(false)
			.HasMaxLength(3)
			.IsFixedLength();
		builder.Property(transaction => transaction.BranchCode!)
			.IsBranchCode()
			.IsRequired();
		builder.Property(transaction => transaction.OccurredAtUtc)
			.HasConversion(new UtcDateTimeOffsetConverter())
			.HasColumnName("OccurredAtUtc")
			.HasColumnType("datetime2(3)")
			.IsRequired();
		builder.Property(transaction => transaction.PaymentStatus)
			.IsEnumCode("Status")
			.HasDefaultValue(Domain.Enums.TransactionPaymentStatus.Open)
			.HasSentinel(Domain.Enums.TransactionPaymentStatus.Open);
		builder.Property<string?>(ReversalReasonField)
			.HasColumnName("ReversalReason")
			.HasMaxLength(500);
		builder.HasIndex(transaction => new { transaction.BranchCode, transaction.OccurredAtUtc })
			.IncludeProperties("PaymentStatus", "Currency");
		builder.Property<byte[]>("RowVersion").IsRowVersion().IsRequired();
		builder.HasAuditColumns();

		builder.OwnsOne(transaction => transaction.SaleDetails, details =>
		{
			details.Property(value => value.CounterTerminalId)
				.IsCode(20, "CounterId");
			details.Property(value => value.ClerkStaffId)
				.IsCode(50, "ClerkStaffId");
			details.Property(value => value.PaymentMethod)
				.HasColumnName("PaymentMethod")
				.HasMaxLength(50);
			details.HasOne<Staff>()
				.WithMany()
				.HasForeignKey(value => value.ClerkStaffId)
				.OnDelete(DeleteBehavior.Restrict);
		});

		builder.OwnsMany<TransactionTaxRate>(TaxRatesField, rate =>
		{
			rate.ToTable("TransactionTaxRates", table =>
			{
				table.HasCheckConstraint(
					"CK_TransactionTaxRates_Rate", "[Rate] >= 0");
				table.HasCheckConstraint(
					"CK_TransactionTaxRates_TaxCategory",
					"[TaxCategory] IN ('Standard', 'Reduced', 'ZeroRated')");
			});
			rate.WithOwner().HasForeignKey("TransactionId");
			rate.Property(value => value.Category).IsEnumCode("TaxCategory");
			rate.HasKey("TransactionId", nameof(TransactionTaxRate.Category));
			rate.Property(value => value.Rate)
				.HasConversion(new TrailingZeroConverter())
				.HasPrecision(9, 6);
			rate.HasAuditColumns();
		});

		builder.HasMany(transaction => transaction.LineItems)
			.WithOne()
			.HasForeignKey("TransactionId")
			.IsRequired()
			.OnDelete(DeleteBehavior.Restrict);

		builder.HasOne<Branch>()
			.WithMany()
			.HasForeignKey(transaction => transaction.BranchCode)
			.HasPrincipalKey(branch => branch.Code)
			.OnDelete(DeleteBehavior.Restrict);

		builder.Ignore(transaction => transaction.TaxRates);
		builder.Ignore(transaction => transaction.Notifications);
		builder.Ignore(transaction => transaction.Subtotal);
		builder.Ignore(transaction => transaction.Tax);
		builder.Ignore(transaction => transaction.Total);
	}
}

public sealed class TransactionLineConfiguration
	: IEntityTypeConfiguration<TransactionLineItem>
{
	public void Configure(EntityTypeBuilder<TransactionLineItem> builder)
	{
		builder.ToTable("TransactionLines", table =>
		{
			table.HasCheckConstraint(
				"CK_TransactionLines_Quantity", "[Quantity] > 0");
			table.HasCheckConstraint(
				"CK_TransactionLines_UnitPrice", "[UnitPrice] >= 0");
			table.HasCheckConstraint(
				"CK_TransactionLines_LineType",
				"[LineType] IN ('Goods', 'Service', 'MoneyOrder')");
			table.HasCheckConstraint(
				"CK_TransactionLines_TaxCategory",
				"[TaxCategory] IN ('Standard', 'Reduced', 'ZeroRated')");
			table.HasCheckConstraint(
				"CK_TransactionLines_MoneyOrder",
				"([LineType] = 'MoneyOrder' AND [MoneyOrderId] IS NOT NULL) " +
				"OR ([LineType] <> 'MoneyOrder' AND [MoneyOrderId] IS NULL)");
		});
		builder.Property<long>("TransactionLineId").UseIdentityColumn();
		builder.HasKey("TransactionLineId");

		builder.Property(line => line.Description).HasMaxLength(300);
		builder.Property(line => line.Type).IsEnumCode("LineType");
		builder.ComplexProperty(
			line => line.UnitPrice,
			money => money.IsMoney("UnitPrice", "Currency"));
		builder.Property(line => line.Quantity);
		builder.Property(line => line.TaxCategory).IsEnumCode("TaxCategory");
		builder.Property(line => line.ProductSku!).IsSku().IsRequired(false);
		builder.HasAuditColumns();

		builder.HasOne<Product>()
			.WithMany()
			.HasForeignKey(line => line.ProductSku)
			.HasPrincipalKey(product => product.Sku)
			.OnDelete(DeleteBehavior.Restrict);

		builder.Property<string?>("ShipmentId")
			.IsUnicode(false)
			.HasMaxLength(50);
		// UnitPrice is also included, in the AddPerformanceIndexes migration, because
		// IncludeProperties cannot name a complex property.
		builder.HasIndex("TransactionId")
			.IncludeProperties("Type", "Quantity", "TaxCategory", "ShipmentId");
		builder.HasOne(line => line.ShippingItem)
			.WithOne()
			.HasForeignKey<TransactionLineItem>("ShipmentId")
			.OnDelete(DeleteBehavior.Restrict);

		builder.HasOne(line => line.MoneyOrder)
			.WithOne()
			.HasForeignKey<TransactionLineItem>("MoneyOrderId")
			.OnDelete(DeleteBehavior.Restrict);

		builder.Ignore(line => line.Subtotal);
	}
}

public sealed class PaymentConfiguration : IEntityTypeConfiguration<Payment>
{
	public void Configure(EntityTypeBuilder<Payment> builder)
	{
		builder.ToTable("Payments", table =>
		{
			table.HasCheckConstraint("CK_Payments_Amount", "[Amount] > 0");
			table.HasCheckConstraint(
				"CK_Payments_EntryType",
				"[EntryType] IN ('Payment', 'Refund')");
		});
		builder.HasKey(payment => payment.Id);
		builder.Property(payment => payment.Id)
			.HasColumnName("PaymentId")
			.ValueGeneratedNever();

		builder.Property(payment => payment.Type).IsEnumCode("EntryType");
		builder.ComplexProperty(
			payment => payment.Amount,
			money => money.IsMoney("Amount", "Currency"));
		builder.Property(payment => payment.PaymentMethod)
			.HasColumnName("PaymentMethod")
			.HasMaxLength(50);
		builder.Property(payment => payment.RecordedAtUtc)
			.IsUtcDateTime("RecordedAtUtc");
		builder.HasAuditColumns();

		builder.HasOne<TransactionBasket>()
			.WithMany()
			.HasForeignKey(payment => payment.TransactionId)
			.OnDelete(DeleteBehavior.Restrict);
	}
}
